JSON_SCHEMA_INSTRUCTION = """

## 输出格式要求

你必须严格按以下 JSON schema 输出，**只输出纯 JSON，不要用 `````` 包裹，不要加任何解释文字**：

```json
{
  "overall_assessment": "一两句话的总体评价",
  "score": 7.5,
  "strengths": ["优点1", "优点2"],
  "issues": [
    {
      "level": 2,
      "severity": "warning",
      "location": "第3段开头",
      "description": "具体问题描述，要清晰具体",
      "suggestion": "修改建议",
      "before_text": "修改前的原文片段（仅 level 1/2 时填写）",
      "after_text": "修改后的文本（仅 level 1/2 时填写）"
    }
  ]
}
```

字段说明：
- **score**: 0-10 的浮点数，不要固定为 5.0，要给出真实的评分
- **level**: 1=严重错误（可自动修改）、2=需要用户确认、3=仅供参考
- **severity**: "critical" / "warning" / "info"
- **before_text** 和 **after_text**: 仅在 level 为 1 或 2 时填写原文片段和修改后文本
- **克制审稿原则（防无限挑刺）**：审稿重点在于防范事实硬伤与逻辑断层。凡属作者个人修辞风格选择且未引起理解障碍者，一律视为合格。若文本通顺无硬伤，**必须返回 issues: [] 空数组**（空数组是最高评价，严禁为了凑数或证明审稿工作量而刻意找茬）。
- **数量上限**：最多仅报告最严重的 1~2 个关键硬伤（严禁汇报琐碎的主观修辞偏好）；description / suggestion 各一句话；before_text / after_text 各不超过 100 字；同一问题只报一次。

重要：只输出纯 JSON，不要用 `````` 包裹，不要加解释文字。"""

